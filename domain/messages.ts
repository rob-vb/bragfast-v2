/** "Foto 2 van 5" */
export function photoPosition(locale: Locale, n: number, total: number): string {
  return locale === "en" ? `Photo ${n} of ${total}` : `Foto ${n} van ${total}`;
}

export function shortDate(locale: Locale, at: number): string {
  return new Intl.DateTimeFormat(locale === "en" ? "en-GB" : "nl-NL", {
    day: "numeric",
    month: "short",
    year: "numeric",
    timeZone: "Europe/Amsterdam",
  }).format(at);
}

export function likeCountLabel(locale: Locale, count: number): string {
  if (locale === "en") {
    if (count === 1) {
      return "1 like";
    }
    return `${count} likes`;
  }
  if (count === 1) {
    return "1 like";
  }
  return `${count} likes`;
}

/** "12 likes via deze foto": likes on the spot that came through one photo */
export function photoLikesLabel(locale: Locale, count: number): string {
  const likes = likeCountLabel(locale, count);
  return locale === "en" ? `${likes} via this photo` : `${likes} via deze foto`;
}

/** "3 anderen": the people a credit line leaves unnamed */
export function othersLabel(locale: Locale, count: number): string {
  if (locale === "en") {
    return count === 1 ? "1 other" : `${count} others`;
  }
  return count === 1 ? "1 ander" : `${count} anderen`;
}

/** The word under a count set on its own: "plekken" in "3 plekken". */
export function spotNoun(locale: Locale, count: number): string {
  if (locale === "en") {
    return count === 1 ? "spot" : "spots";
  }
  return count === 1 ? "plek" : "plekken";
}

export function cityNoun(locale: Locale, count: number): string {
  if (locale === "en") {
    return count === 1 ? "city" : "cities";
  }
  return count === 1 ? "stad" : "steden";
}

/** "in 2 steden" */
export function inCitiesLabel(locale: Locale, count: number): string {
  return `in ${count} ${cityNoun(locale, count)}`;
}

/** "#2 op de leaderboard" */
export function leaderboardRankLabel(locale: Locale, rank: number): string {
  return locale === "en"
    ? `#${rank} on the leaderboard`
    : `#${rank} op de leaderboard`;
}

/** "2503 steden": every woonplaats has a board */
export function townCountLabel(locale: Locale, count: number): string {
  const n = count.toLocaleString(locale === "en" ? "en-GB" : "nl-NL");
  return locale === "en" ? `${n} cities` : `${n} steden`;
}

/** Announced when the example board's order changes */
export function demoTopLabel(locale: Locale, name: string): string {
  return locale === "en" ? `${name} is now on top` : `${name} staat nu bovenaan`;
}
