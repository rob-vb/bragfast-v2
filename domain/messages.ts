export type Locale = "nl" | "en";

const catalogs: Record<Locale, Record<MessageKey, string>> = {
  nl: nlMessages,
  en: enMessages,
};

export function t(locale: Locale, key: MessageKey): string {
  return catalogs[locale][key];
}

export function boardCityLabel(locale: Locale, count: number): string {
  if (locale === "en") {
    if (count === 1) {
      return "1 spot on the board";
    }
    return `${count} spots on the board`;
  }
  if (count === 1) {
    return "1 plek op de board";
  }
  return `${count} plekken op de board`;
}

export function uniqueSpotsLabel(locale: Locale, count: number): string {
  if (locale === "en") {
    if (count <= 0) {
      return "No spots yet";
    }
    if (count === 1) {
      return "1 spot";
    }
    return `${count} spots`;
  }
  if (count <= 0) {
    return "Nog geen plekken";
  }
  if (count === 1) {
    return "1 plek";
  }
  return `${count} plekken`;
}

/** "Ontbijt en brunch in Gouda": the board's title in search results */
export function cityMetaTitle(locale: Locale, city: string): string {
  return locale === "en" ? `Breakfast and brunch in ${city}` : `Ontbijt en brunch in ${city}`;
}

export function cityMetaDescription(locale: Locale, city: string, count: number): string {
  if (locale === "en") {
    if (count <= 0) {
      return `No breakfast or brunch spots in ${city} yet. Put the first one on the board with a photo in the app.`;
    }
    return `Breakfast and brunch in ${city}: ${uniqueSpotsLabel(locale, count)} ranked by visitors' likes, with photos from the app.`;
  }
  if (count <= 0) {
    return `Nog geen ontbijt- of brunchplekken in ${city}. Zet de eerste op de board met een foto in de app.`;
  }
  return `Ontbijt en brunch in ${city}: ${uniqueSpotsLabel(locale, count)} op volgorde van likes van bezoekers, met foto's uit de app.`;
}

export function spotMetaDescription(
  locale: Locale,
  spot: { name: string; address: string; likeCount: number },
): string {
  const likes = likeCountLabel(locale, spot.likeCount);
  return locale === "en"
    ? `Breakfast and brunch at ${spot.name}, ${spot.address}. ${likes} from visitors on brag.fast.`
    : `Ontbijt en brunch bij ${spot.name}, ${spot.address}. ${likes} van bezoekers op brag.fast.`;
}

export function photoCountLabel(locale: Locale, count: number): string {
  if (locale === "en") {
    if (count <= 0) {
      return "No photos yet";
    }
    return count === 1 ? "1 photo" : `${count} photos`;
  }
  if (count <= 0) {
    return "Nog geen foto's";
  }
  return count === 1 ? "1 foto" : `${count} foto's`;
}

/** "2 ontdekt": spots the account put on brag.fast */
export function discoveredCountLabel(locale: Locale, count: number): string {
  return locale === "en" ? `${count} discovered` : `${count} ontdekt`;
}

export function passportMetaDescription(
  locale: Locale,
  slug: string,
  photoCount: number,
  discoveredCount: number,
): string {
  const photos = photoCountLabel(locale, photoCount);
  if (locale === "en") {
    const found =
      discoveredCount > 0
        ? `, ${discoveredCount} ${spotNoun(locale, discoveredCount)} discovered`
        : "";
    return `@${slug}'s passport on brag.fast: ${photos.toLowerCase()} of breakfast and brunch${found}.`;
  }
  const found =
    discoveredCount > 0
      ? `, ${discoveredCount} ${spotNoun(locale, discoveredCount)} ontdekt`
      : "";
  return `Het paspoort van @${slug} op brag.fast: ${photos.toLowerCase()} van ontbijt en brunch${found}.`;
}

